-- 計分改版 v3:評分梯度重寫，進步門檻 10 → 3
--
-- 背景（實測 525 個子分數）
--   子分數  0-2:0 次   3:4 次   4:25 次   5:112 次   6:252 次   7:132 次   8-10:0 次
--   模型從來沒給過 0、1、2、8、9、10，94% 擠在 5、6、7。
--   總分 = 各項加權平均 × 10，所以總分永遠落在 48-66，
--   刻度上面 30 分與下面 45 分是物理上到不了的。
--   5 月平均 72.8 → 11 月 58.6 的掉幅，時間點正好是 8 月改成 v2，
--   不是使用者變不健康。
--
--   病灶在 prompt 的梯度表：「7-9 分:輕微問題,基本健康」與
--   「4-6 分:輕微失調,需注意」在中文裡幾乎同義，模型分不出界線就往下靠；
--   而 10 分要求「完全正常」，真實的臉不可能完全沒東西。
--   v3 改成有明確區隔的錨點，並明講「作息正常、沒有不適的人多數項目落在 7-8」。

-- ① 版本號跟著跳
--
-- ⚠️ 這一步不能省。rpc_settle_score 只拿同版本的分數相減
--    （它自己的註解：「不然是拿兩把尺相減」）。
--    不跳號的話，舊的 v2 基準（48-66）會對上新的 v3 分數，
--    每個人都憑空「進步」十幾分，獎勵全部誤發。
--
-- 代價：跳號之後，既有的 35 筆 v2 紀錄不再是任何人的基準，
--       要等各自再做一次檢測、產生 v3 紀錄，月結才有東西可比。
create or replace function public.current_score_version()
returns integer
language sql
immutable
set search_path to 'public', 'pg_catalog'
as $function$ select 3 $function$;

-- ② 進步門檻 10 → 3
--
-- 10 分在舊刻度上幾乎不可能：全體使用者從最低到最高只有 18 分，
-- 進步 10 分等於一個月內從後段班衝到前段班。
-- 實際資料裡同月做過兩次的 6 個人，最大落差是 7 分，其餘 5、5、2、2、1。
-- sb_score_snapshots 到今天是 0 筆，這個獎勵一次都沒發生過。
update public.sb_point_rules
   set points = 3
 where rule_key = 'score_up_threshold';
