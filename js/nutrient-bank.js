/**
 * 今天考哪一題 —— 用台北日期決定,所以同一天所有人拿到同一題。
 * 隨機挑的話,分享出去會對不上,「今天這題好難」就沒有人接得下去。
 */
function todayIndex(taipeiISODate, total) {
  // 日期字串直接折成一個數,不需要密碼學等級的雜湊,只要分佈夠散。
  let h = 0;
  for (let i = 0; i < taipeiISODate.length; i++) {
    h = (h * 31 + taipeiISODate.charCodeAt(i)) >>> 0;
  }
  return h % total;
}
